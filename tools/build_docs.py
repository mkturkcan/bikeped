#!/usr/bin/env python3
"""Build the bikeped documentation site.

The site is MkDocs Material, configured in ``mkdocs.yml`` with hand-written
pages in ``docs_src/``. This script adds what is derived from code and then
runs MkDocs:

1. Writes ``docs_src/_generated/``: the ``--help`` text of every command line
   tool (``cli/<name>.txt``) and one scenario catalog table per suite of
   ``bikeped.scenarios`` (``scenarios/<suite>.md``). Hand-written pages pull
   these in with snippet includes. Nothing outside ``_generated/`` is written,
   and a tool that cannot run here (for example one that needs ``carla``)
   gets no file, so its include renders empty.
2. Runs ``mkdocs build`` into the output directory (``docs/`` by default).
3. Copies the browser simulator (``simulator/``) to ``<out>/simulator/`` and
   keeps ``<out>/.nojekyll`` so GitHub Pages serves the folder as is.

Usage::

    python tools/build_docs.py                 # build into docs/
    python tools/build_docs.py --strict        # fail on any MkDocs warning
    python tools/build_docs.py --out /tmp/site # build somewhere else
    python tools/build_docs.py --serve         # live preview on http://127.0.0.1:8000
    python tools/build_docs.py --open          # build, then open the result in a browser
"""

from __future__ import annotations

import argparse
import html
import shutil
import subprocess
import sys
import webbrowser
from pathlib import Path
from typing import Dict, List, Optional, Sequence

ROOT = Path(__file__).resolve().parent.parent
DOCS_SRC = ROOT / "docs_src"
GENERATED = DOCS_SRC / "_generated"
SIMULATOR = ROOT / "simulator"
HEADER = "<!-- Generated by tools/build_docs.py from {source}. Do not edit. -->\n"

#: Help text to capture: output name -> command, run from the repository root.
CLI_COMMANDS: Dict[str, List[str]] = {
    "decision_testbench": ["decision_testbench.py", "--help"],
    "sim_visualizer": ["sim_visualizer.py", "--help"],
    "run_experiments": ["run_experiments.py", "--help"],
    "calibrate_fisheye": ["calibration/calibrate_fisheye.py", "--help"],
    "capture_calibration": ["calibration/capture_calibration.py", "--help"],
    "compare_fisheye_models": ["calibration/compare_fisheye_models.py", "--help"],
    "eval_models": ["tools/eval_models.py", "--help"],
    "bikeped_scenarios": ["-m", "bikeped.scenarios", "--help"],
    "bikeped_sim": ["-m", "bikeped.sim", "--help"],
}
SCENARIO_SUBCOMMANDS = ("list", "show", "validate", "evaluate", "generate", "export")
SIM_SUBCOMMANDS = ("probe", "server", "presets", "render", "export")
for _sub in SCENARIO_SUBCOMMANDS:
    CLI_COMMANDS[f"bikeped_scenarios_{_sub}"] = ["-m", "bikeped.scenarios", _sub, "--help"]
for _sub in SIM_SUBCOMMANDS:
    CLI_COMMANDS[f"bikeped_sim_{_sub}"] = ["-m", "bikeped.sim", _sub, "--help"]


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def generate_cli_help(python: str) -> List[str]:
    """Capture ``--help`` of every tool into ``_generated/cli/<name>.txt``.

    The text is written without a header because it is included inside a
    code fence. Returns the names that could not be captured.
    """
    missing = []
    for name, args in CLI_COMMANDS.items():
        try:
            proc = subprocess.run([python, *args], cwd=ROOT, capture_output=True,
                                  text=True, timeout=60)
        except subprocess.TimeoutExpired:
            missing.append(name)
            continue
        out = proc.stdout.strip()
        if proc.returncode != 0 or not out.startswith("usage:"):
            missing.append(name)
            continue
        # argparse wraps to $COLUMNS; normalise the program name for -m modules.
        out = out.replace("usage: __main__.py", "usage: python -m " + " ".join(args[1:2]))
        _write(GENERATED / "cli" / f"{name}.txt", out + "\n")
    return missing


def _thumb(scenario_id: str, depth: int) -> str:
    """HTML for a catalog thumbnail, or an empty placeholder if it is missing."""
    rel = Path("assets/scenarios") / f"{scenario_id}.svg"
    if (DOCS_SRC / rel).exists():
        src = "../" * depth + rel.as_posix()
        # Markdown image syntax so MkDocs resolves and checks the path.
        return f'![]({src}){{ .scenario-thumb loading=lazy }}'
    return '<span class="scenario-thumb--missing" aria-hidden="true"></span>'


def _cell(text: object) -> str:
    return html.escape(str(text)).replace("|", "\\|").replace("\n", " ")


def generate_scenario_catalog() -> Optional[List[str]]:
    """Write one Markdown catalog table per suite of ``bikeped.scenarios``.

    The tables are included from pages one directory below the docs root
    (``scenarios/*.md``), so thumbnail paths are relative to that depth.
    Returns the suites written, or ``None`` if the library is not importable.
    """
    sys.path.insert(0, str(ROOT))
    try:
        from bikeped.scenarios import get_suite, list_suites
        from decision_testbench import get_scenario_duration
    except ImportError:
        return None
    written = []
    for suite in list_suites():
        try:
            scenarios = get_suite(suite)
        except Exception as exc:  # a suite under development must not stop the build
            print(f"[docs] suite '{suite}' skipped: {exc}")
            continue
        rows = [
            HEADER.format(source=f"bikeped.scenarios suite '{suite}'"),
            "| | Scenario | Family | Expected | Duration | Agents |",
            "|---|---|---|---|---|---|",
        ]
        for sc in scenarios:
            sid = sc.get("id", "")
            kinds = [a.get("model") or a.get("type", "") for a in sc.get("agents", [])]
            agents = ", ".join(f"{kinds.count(k)} {k}" for k in dict.fromkeys(kinds))
            expected = sc.get("expected_dominant", "")
            rows.append(
                f"| {_thumb(sid, 1)} "
                f"| {_cell(sc.get('name', sid))} `{_cell(sid)}`"
                f"<br><span class=\"catalog-desc\">{_cell(sc.get('description', ''))}</span> "
                f"| {_cell(sc.get('family', ''))} "
                f"| <span class=\"state state-{expected}\">{expected}</span> "
                f"| {get_scenario_duration(sc):.1f} s "
                f"| {_cell(agents)} |"
            )
        _write(GENERATED / "scenarios" / f"{suite}.md", "\n".join(rows) + "\n")
        written.append(suite)
    return written


def copy_simulator(out: Path) -> None:
    """Copy the browser simulator into the built site and keep ``.nojekyll``."""
    if SIMULATOR.is_dir():
        dest = out / "simulator"
        if dest.exists():
            shutil.rmtree(dest)
        shutil.copytree(SIMULATOR, dest)
    (out / ".nojekyll").touch()


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Build the bikeped documentation site.")
    parser.add_argument("--serve", action="store_true",
                        help="Generate pages, then run 'mkdocs serve' for a live preview.")
    parser.add_argument("--open", action="store_true",
                        help="Open the built site in the default browser.")
    parser.add_argument("--strict", action="store_true",
                        help="Treat MkDocs warnings (broken links, missing pages) as errors.")
    parser.add_argument("--out", type=Path, default=ROOT / "docs",
                        help="Output directory (default: docs/).")
    parser.add_argument("--skip-generate", action="store_true",
                        help="Build from the existing docs_src/_generated/ files.")
    args = parser.parse_args(argv)

    if not args.skip_generate:
        missing = generate_cli_help(sys.executable)
        if missing:
            print(f"[docs] no --help captured for: {', '.join(missing)}")
        suites = generate_scenario_catalog()
        if suites is None:
            print("[docs] scenario catalog skipped: bikeped.scenarios is not importable")
        else:
            print(f"[docs] scenario catalog: {', '.join(suites) or 'no suite could be built'}")

    mkdocs = [sys.executable, "-m", "mkdocs"]
    if args.serve:
        return subprocess.call([*mkdocs, "serve", "-f", str(ROOT / "mkdocs.yml")], cwd=ROOT)

    out = args.out.resolve()
    cmd = [*mkdocs, "build", "-f", str(ROOT / "mkdocs.yml"), "-d", str(out)]
    if args.strict:
        cmd.append("--strict")
    code = subprocess.call(cmd, cwd=ROOT)
    if code != 0:
        return code
    copy_simulator(out)
    print(f"[docs] site written to {out}")
    if args.open:
        landing = out / "index.html"
        webbrowser.open((landing if landing.exists() else out / "start" / "index.html").as_uri())
    return 0


if __name__ == "__main__":
    sys.exit(main())
